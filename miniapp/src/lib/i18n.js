/** Mahsulot nomini tanlangan tilda qaytaradi */
export const pick = (obj, field, lang) => {
  if (!obj) return '';
  if (lang === 'ru') {
    const ru = obj[`${field}Ru`];
    if (ru) return ru;
  }
  return obj[field] || '';
};
